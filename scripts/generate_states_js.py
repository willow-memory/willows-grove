#!/usr/bin/env python3
"""Generate web/lib/states.js from the one script's ``onescript/states.py``.

Flatten-2 F9: the three states have one home, ``onescript/states.py`` (the
operator: "Using the onescript at every path."). Grove's browser modules
import ``web/lib/states.js`` instead of restating the words; this file is
derived, never hand-kept. ``--check`` exits 1 when the committed copy is
stale; tests/test_states_js_parity.py holds it in CI.

``LOADING`` is UI-only (D-f): a display condition before any answer. It is
emitted apart from ``STATES`` and is never a reader's state.

The one script is reached only through ``grove/three_states.py`` and so
``grove/onescript_reach.py`` (``$WILLOW_BOT_ROOT``, else the reach's rule).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "web" / "lib" / "states.js"


def render() -> str:
    """The text of states.js, from the states module the one reach finds."""
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from grove import three_states

    st = three_states._one_script_states()
    names = {"populated": "POPULATED", "empty": "EMPTY", "unreachable": "UNREACHABLE"}
    assert tuple(names) == tuple(st.STATES), "states.py changed: extend this map"
    lines = [
        "// b17: WGRV1 ΔΣ=42",
        "// GENERATED by scripts/generate_states_js.py from the one script's",
        "// onescript/states.py (flatten-2 F9). Do not edit; regenerate.",
        "//",
        "// The three states, once. Every reader answers one of these, never",
        "// collapsed (INVARIANTS.md §1).",
    ]
    for word, const in names.items():
        lines.append(f'export const {const} = "{word}";')
    lines += [
        "export const STATES = Object.freeze([" + ", ".join(names.values()) + "]);",
        "",
        "// UI-only (D-f): a display condition before any answer arrives. It is",
        "// NOT a state: never stored, sent, or compared as a reader's state.",
        'export const LOADING = "loading";',
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="exit 1 if stale")
    args = ap.parse_args(argv)

    try:
        text = render()
    except Exception as e:  # unreachable one script: say so, write nothing
        print(f"generate_states_js: unreachable: {e}", file=sys.stderr)
        return 2
    if args.check:
        have = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else None
        if have != text:
            print(
                f"{OUTPUT} is stale; run scripts/generate_states_js.py", file=sys.stderr
            )
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
